def _origin_list(*values):
    origins = []
    for value in values:
        for item in (value or '').split(','):
            origin = item.strip().rstrip('/')
            if origin and not origin.startswith(('http://', 'https://')):
                origin = f'https://{origin}'
            if origin and origin not in origins:
                origins.append(origin)
    return origins


