def _host_list(*values):
    hosts = []
    for value in values:
        for item in (value or '').split(','):
            host = item.strip().lower().removeprefix('https://').removeprefix('http://').strip('/')
            if host and host not in hosts:
                hosts.append(host)
    return hosts


